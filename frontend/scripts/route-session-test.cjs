const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

(async () => {
  const source = fs.readFileSync(path.join(__dirname, '../utils/routeSession.js'), 'utf8');
  const { numberVisits, numberOptimizedVisits, restoreRouteSession } = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
  const day = '2026-09-27';
  const rows = [{ id: 1, status: 'complete' }, { id: 2, status: 'complete' }, { id: 3, status: 'pending' }];
  const session = { day, order: ['1', '2', '3'], optimized: true, isGuiding: true, currentSegmentIndex: 1, routeSegments: [{ to: 1 }, { to: 2 }, { to: 3 }] };
  const restored = restoreRouteSession(rows, session, day);
  assert.deepEqual(restored.locations.map(row => row.id), [3, 1, 2]);
  assert.deepEqual(restored.locations.map(row => row.markerNumber), [3, 1, 2]);
  assert.deepEqual(restored.segments, [{ to: 3 }]);
  assert.equal(restored.currentSegmentIndex, 0);
  assert.equal(restored.isGuiding, true);
  assert.equal(restoreRouteSession(rows, session, '2026-09-28'), null);
  const expanded = restoreRouteSession([...rows, { id: 4, status: 'pending' }], session, day);
  assert.deepEqual(expanded.locations.map(row => row.id), [3, 4, 1, 2]);
  assert.deepEqual(expanded.segments, [{ to: 3 }, null]);
  assert.equal(expanded.isGuiding, true);
  assert.equal(expanded.currentSegmentIndex, 0);
  assert.equal(restoreRouteSession(rows, { ...session, routeSegments: [] }, day), null);
  assert.equal(restoreRouteSession(rows.map(row => ({ ...row, status: 'complete' })), session, day).optimized, false);
  const pending = rows.map(row => ({ ...row, status: 'pending' }));
  assert.equal(restoreRouteSession(pending, session, day).currentSegmentIndex, 1);
  const numbered = numberVisits(pending);
  const optimizedOrder = [numbered[2], numbered[0], numbered[1]];
  assert.deepEqual(numberVisits(optimizedOrder).map(row => row.markerNumber), [3, 1, 2]);
  assert.deepEqual(numberOptimizedVisits(optimizedOrder, []).map(row => row.markerNumber), [1, 2, 3]);
  const completedPrefix = [{ id: 1, markerNumber: 1, status: 'complete' }, { id: 2, markerNumber: 2, status: 'complete' }];
  const reoptimized = numberOptimizedVisits([{ id: 5 }, { id: 3 }, { id: 4 }], completedPrefix);
  assert.deepEqual(reoptimized.map(row => row.markerNumber), [3, 4, 5, 1, 2]);
  assert.deepEqual(numberOptimizedVisits([{ id: 2 }, { id: 4 }], [completedPrefix[0], { id: 3, markerNumber: 3, status: 'complete' }]).map(row => row.markerNumber), [2, 4, 1, 3]);
  const savedNumbers = Object.fromEntries(numbered.map(row => [String(row.id), row.markerNumber]));
  const restart = restoreRouteSession(rows, { ...session, order: ['3', '1', '2'], visitNumbers: savedNumbers }, day);
  assert.equal(restart.locations.find(row => row.id === 1).markerNumber, 1);
  assert.equal(restart.locations.find(row => row.id === 3).markerNumber, 3);
  assert.deepEqual(numberVisits([...numbered, { id: 4 }]).map(row => row.markerNumber), [1, 2, 3, 4]);
  console.log('Route session checks passed');
})().catch(error => { console.error(error); process.exitCode = 1; });
