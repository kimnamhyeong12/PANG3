const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
(async () => {
  const routeSource = fs.readFileSync(path.join(__dirname, '../utils/routeSession.js'), 'utf8');
  const routeUrl = `data:text/javascript;base64,${Buffer.from(routeSource).toString('base64')}`;
  const source = fs.readFileSync(path.join(__dirname, '../utils/workPlan.js'), 'utf8').replace("'./routeSession'", JSON.stringify(routeUrl));
  const { assignmentKey, splitWorkPlan } = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
  const { restoreRouteSession } = await import(routeUrl);
  const day = '2026-09-27';
  const row = { id: 1, assignedAt: 'v1', scheduledDate: day, status: 'pending' };
  const key = assignmentKey(row);
  let plan = splitWorkPlan([row], {}, day);
  assert.equal(plan.map.length, 0);
  assert.equal(plan.incoming.length, 1);
  plan = splitWorkPlan([row], { [key]: 'later' }, day);
  assert.equal(plan.pending.length, 1);
  assert.equal(plan.incoming.length, 0);
  plan = splitWorkPlan([row], { [key]: day }, day);
  assert.equal(plan.map.length, 1);
  assert.equal(plan.pending.length, 0);
  plan = splitWorkPlan([row], { [key]: day }, '2026-09-28');
  assert.equal(plan.map.length, 0);
  assert.equal(plan.pending.length, 1);
  plan = splitWorkPlan([{ ...row, status: 'working' }], { [key]: day }, '2026-09-28');
  assert.equal(plan.pending.length, 1);
  plan = splitWorkPlan([{ ...row, status: 'complete' }], { [key]: day }, day);
  assert.equal(plan.map.length, 1);
  assert.equal(plan.pending.length, 0);
  assert.equal(plan.incoming.length, 0);
  plan = splitWorkPlan([{ ...row, assignedAt: 'v2' }], { [key]: day }, day);
  assert.equal(plan.incoming.length, 1);
  plan = splitWorkPlan([row], {}, day, [row]);
  assert.equal(plan.map.length, 1);
  const newWork = { ...row, id: 2 };
  const savedChoices = JSON.parse(JSON.stringify({ [key]: day }));
  plan = splitWorkPlan([row, newWork], savedChoices, day);
  assert.deepEqual(plan.map.map(item => item.id), [1]);
  assert.deepEqual(plan.incoming.map(item => item.id), [2]);
  const personal = splitWorkPlan([newWork], {}, day, [], { autoAddToday: true });
  assert.deepEqual(personal.map.map(item => item.id), [2]);
  assert.equal(personal.pending.length, 0);
  assert.equal(personal.incoming.length, 0);
  assert.equal(splitWorkPlan([newWork], { [assignmentKey(newWork)]: 'later' }, day, [],
    { autoAddToday: true }).pending.length, 1);
  assert.equal(splitWorkPlan([{ ...newWork, scheduledDate: '2026-09-28' }], {}, day, [],
    { autoAddToday: true }).map.length, 0);
  const session = { day, order: ['1'], optimized: true, isGuiding: true, currentSegmentIndex: 0, routeSegments: [{ to: 1 }] };
  let route = restoreRouteSession(plan.map, session, day);
  assert.deepEqual(route.segments, [{ to: 1 }]);
  assert.equal(route.isGuiding, true);
  plan = splitWorkPlan([row, newWork], { ...savedChoices, [assignmentKey(newWork)]: day }, day);
  route = restoreRouteSession(plan.map, session, day);
  assert.deepEqual(route.locations.map(item => item.id), [1, 2]);
  assert.deepEqual(route.segments, [{ to: 1 }, null]);
  assert.equal(route.currentSegmentIndex, 0);
  const overdue = { ...row, scheduledDate: '2026-09-26' };
  assert.equal(splitWorkPlan([overdue], savedChoices, day).map[0].scheduledDate, day);
  console.log('Work plan checks passed');
})().catch(error => { console.error(error); process.exitCode = 1; });
