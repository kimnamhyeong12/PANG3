const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
(async () => {
  const code = fs.readFileSync(path.join(__dirname, '../utils/placeSearch.js'), 'utf8');
  const { mergePlaceResults, explicitRegion, distanceMeters, isRegisteredPlace, searchPlaces, sheetDrag, isNearbyCategoryQuery, searchViewportPlaces } = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
  assert.equal(explicitRegion('부산 동아대'), '부산'); assert.equal(explicitRegion('서울역'), '');
  const busan = { id: '1', place_name: '동아대학교 부민캠퍼스', address_name: '부산 서구 구덕로 225', x: '129.019', y: '35.103' };
  const seoul = { id: '2', place_name: '부산식당', address_name: '서울 강남구', x: '127.0', y: '37.5' };
  assert.equal(mergePlaceResults([], [seoul, busan], '부산', { lat: 37.5, lng: 127 })[0].id, '1', 'explicit region beats nearby name');
  assert.equal(mergePlaceResults([], [busan, seoul], '식당', { lat: 37.5, lng: 127 })[0].id, '1', 'distance must not override provider relevance');
  const dojo = { ...busan, id: 'dojo', place_name: '동아대 유도관', x: '129.0', y: '35.1' };
  assert.deepEqual(mergePlaceResults([], [busan, dojo], '동아대', { lat: 35.1, lng: 129 }).map(item => item.id), ['1', 'dojo'], 'a nearby subsidiary must not displace a higher relevance campus');
  assert.equal(mergePlaceResults([], [busan, busan], '동아대', null).length, 1);
  assert.equal(mergePlaceResults([], Array.from({ length: 20 }, (_, i) => ({ ...busan, id: i, place_name: 'place'+i })), 'place', null).length, 7);
  assert.equal(distanceMeters({ lat: null, lng: null }, { lat: 35, lng: 129 }), null);
  assert.equal(isRegisteredPlace(busan, [{ detailAddress: busan.place_name, lat: 35.103, lng: 129.019 }]), true);
  assert.equal(isRegisteredPlace(busan, [{ detailAddress: busan.place_name, lat: null, lng: null }]), false);
  assert.deepEqual(sheetDrag(300, 0, -100, 300, 1000), { y: 200, scroll: 0 });
  assert.deepEqual(sheetDrag(300, 0, -450, 300, 1000), { y: 0, scroll: 150 });
  assert.deepEqual(sheetDrag(0, 200, 100, 300, 1000), { y: 0, scroll: 100 });
  assert.deepEqual(sheetDrag(0, 200, 350, 300, 1000), { y: 150, scroll: 0 });
  assert.deepEqual(sheetDrag(0, 0, -2000, 300, 600), { y: 0, scroll: 600 });
  process.env.EXPO_PUBLIC_KAKAO_REST_API_KEY = 'test-only';
  assert.equal(isNearbyCategoryQuery('초등학교'), true);
  assert.equal(isNearbyCategoryQuery('근처 초등학교'), true);
  assert.equal(isNearbyCategoryQuery('부산대'), false);
  assert.equal(isNearbyCategoryQuery('근처 세탁소'), true);
  assert.equal(isNearbyCategoryQuery('주변 정비소'), true);
  assert.equal(isNearbyCategoryQuery('내 주변 문구점'), true);
  assert.deepEqual(searchViewportPlaces([busan, seoul]).map(place => place.id), ['1'], 'distant named results do not force a national map extent');
  const categoryUrls = [];
  global.fetch = async url => { categoryUrls.push(url); return { ok: true, json: async () => ({ documents: categoryUrls.length === 1 ? [] : [busan] }) }; };
  assert.equal((await searchPlaces('초등학교', { center: { lat: 35.1, lng: 129 } }))[0].id, '1');
  assert.ok(categoryUrls[0].includes('radius=5000') && categoryUrls[0].includes('sort=distance'));
  assert.ok(categoryUrls[1].includes('radius=10000'), 'empty nearby category search expands gradually');
  await assert.rejects(searchPlaces('초등학교'), /현재 위치/);
  const urls = [];
  global.fetch = async url => { urls.push(url); return { ok: true, json: async () => ({ documents: url.includes('/address.') ? [] : [busan] }) }; };
  assert.equal((await searchPlaces('부산 동아대', { center: { lat: 37.5, lng: 127 } }))[0].id, '1');
  assert.ok(!urls[1].includes('sort=distance'), 'explicit region search must not be biased to current city');
  urls.length = 0; await searchPlaces('동아대', { center: { lat: 35.1, lng: 129 } });
  assert.ok(urls.some(url => url.includes('x=129') && url.includes('sort=accuracy')), 'current coordinates guide provider relevance');
  assert.ok(!urls.some(url => url.includes('radius=')), 'a place outside the current district or 20km remains searchable');
  assert.ok(!urls.some(url => url.includes('sort=distance')));
  global.fetch = async url => ({ ok: true, json: async () => ({ documents: url.includes('/address.') ? [] : url.includes('radius=') ? [busan, dojo] : [seoul, busan] }) });
  assert.deepEqual((await searchPlaces('동아대', { center: { lat: 35.1, lng: 129 } })).map(item => item.id), ['2', '1'], 'provider relevance stays intact without a local-only filter');
  global.fetch = async url => { if (url.includes('radius=')) throw new Error('offline'); return { ok: true, json: async () => ({ documents: url.includes('/address.') ? [] : [busan] }) }; };
  assert.equal((await searchPlaces('동아대', { center: { lat: 35.1, lng: 129 } }))[0].id, '1', 'local search failure falls back to national relevance');
  urls.length = 0;
  global.fetch = async url => { urls.push(url); return { ok: true, json: async () => ({ documents: [] }) }; };
  await searchPlaces('동아대', { center: { lat: null, lng: null } });
  assert.ok(!urls.some(url => url.includes('radius=')), 'missing coordinates must not produce a local search at zero coordinates');
  global.fetch = async url => { if (url.includes('/address.')) throw new Error('offline'); return { ok: true, json: async () => ({ documents: [busan] }) }; };
  assert.equal((await searchPlaces('동아대')).length, 1, 'one API failure retains successful results');
  global.fetch = async () => { throw new Error('offline'); };
  await assert.rejects(searchPlaces('동아대'));
  console.log('Place search checks passed: region ranking, address/place merge, duplicate visits, failure handling, sheet/list gesture handoff');
})().catch(error => { console.error(error); process.exit(1); });
