const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
(async () => {
  const code = fs.readFileSync(path.join(__dirname, '../utils/placeSearch.js'), 'utf8');
  const { mergePlaceResults, explicitRegion, distanceMeters, isRegisteredPlace, searchPlaces, sheetDrag } = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
  assert.equal(explicitRegion('부산 동아대'), '부산'); assert.equal(explicitRegion('서울역'), '');
  const busan = { id: '1', place_name: '동아대학교 부민캠퍼스', address_name: '부산 서구 구덕로 225', x: '129.019', y: '35.103' };
  const seoul = { id: '2', place_name: '부산식당', address_name: '서울 강남구', x: '127.0', y: '37.5' };
  assert.equal(mergePlaceResults([], [seoul, busan], '부산', { lat: 37.5, lng: 127 })[0].id, '1', 'explicit region beats nearby name');
  assert.equal(mergePlaceResults([], [busan, seoul], '식당', { lat: 37.5, lng: 127 })[0].id, '2', 'unspecified region uses distance');
  assert.equal(mergePlaceResults([], [busan, busan], '동아대', null).length, 1);
  assert.equal(mergePlaceResults([], Array.from({ length: 20 }, (_, i) => ({ ...busan, id: i, place_name: 'place'+i })), 'place', null).length, 7);
  assert.equal(distanceMeters({ lat: null, lng: null }, { lat: 35, lng: 129 }), null);
  assert.equal(isRegisteredPlace(busan, [{ detailAddress: busan.place_name, lat: 35.103, lng: 129.019 }]), true);
  assert.equal(isRegisteredPlace(busan, [{ detailAddress: busan.place_name, lat: null, lng: null }]), false);
  assert.deepEqual(sheetDrag(300, 0, -100, 300, 1000), { y: 200, scroll: 0 });
  assert.deepEqual(sheetDrag(300, 0, -450, 300, 1000), { y: 0, scroll: 150 });
  assert.deepEqual(sheetDrag(0, 200, 100, 300, 1000), { y: 0, scroll: 100 });
  assert.deepEqual(sheetDrag(0, 200, 350, 300, 1000), { y: 150, scroll: 0 });
  assert.deepEqual(sheetDrag(0, 0, -2000, 300, 600), { y: 0, scroll: 600 });
  process.env.EXPO_PUBLIC_KAKAO_REST_API_KEY = 'test-only';
  const urls = [];
  global.fetch = async url => { urls.push(url); return { ok: true, json: async () => ({ documents: url.includes('/address.') ? [] : [busan] }) }; };
  assert.equal((await searchPlaces('부산 동아대', { center: { lat: 37.5, lng: 127 } }))[0].id, '1');
  assert.ok(!urls[1].includes('sort=distance'), 'explicit region search must not be biased to current city');
  urls.length = 0; await searchPlaces('동아대', { center: { lat: 35.1, lng: 129 } });
  assert.ok(urls.some(url => url.includes('sort=distance')));
  assert.ok(urls.some(url => url.includes('/keyword.') && !url.includes('sort=distance')), 'accuracy results must also be retained');
  global.fetch = async url => { if (url.includes('/address.')) throw new Error('offline'); return { ok: true, json: async () => ({ documents: [busan] }) }; };
  assert.equal((await searchPlaces('동아대')).length, 1, 'one API failure retains successful results');
  global.fetch = async () => { throw new Error('offline'); };
  await assert.rejects(searchPlaces('동아대'));
  console.log('Place search checks passed: region ranking, address/place merge, duplicate visits, failure handling, sheet/list gesture handoff');
})().catch(error => { console.error(error); process.exit(1); });
