-- PostgreSQL. Run against the intended database after a backup, before deploying the new backend.
-- This creates only the new support table. It does not assign any operator accounts.
CREATE TABLE IF NOT EXISTS support_inquiries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id),
    request_key VARCHAR(80) NOT NULL,
    reply_email VARCHAR(254) NOT NULL,
    category VARCHAR(30) NOT NULL,
    subject VARCHAR(100) NOT NULL,
    message VARCHAR(5000) NOT NULL,
    app_version VARCHAR(80),
    platform VARCHAR(80),
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    answer VARCHAR(5000),
    answered_at TIMESTAMP WITH TIME ZONE,
    answered_by BIGINT REFERENCES users(user_id),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_support_owner_request UNIQUE(user_id, request_key)
);
CREATE INDEX IF NOT EXISTS idx_support_owner_created ON support_inquiries(user_id, created_at);
CREATE INDEX IF NOT EXISTS idx_support_status_created ON support_inquiries(status, created_at);

CREATE TABLE IF NOT EXISTS support_attachments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inquiry_id BIGINT NOT NULL REFERENCES support_inquiries(id),
    name VARCHAR(160) NOT NULL,
    content_type VARCHAR(40) NOT NULL,
    size BIGINT NOT NULL,
    storage_key VARCHAR(120) NOT NULL UNIQUE
);
CREATE INDEX IF NOT EXISTS idx_support_attachment_inquiry ON support_attachments(inquiry_id);
