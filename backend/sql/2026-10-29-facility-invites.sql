-- PostgreSQL. Review and apply to the intended database before backend deployment.
-- No administrator roles or existing public-data records are changed.
CREATE TABLE IF NOT EXISTS facility_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(40) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS facility_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id),
    request_key VARCHAR(80) NOT NULL,
    name VARCHAR(100) NOT NULL,
    kind VARCHAR(40) NOT NULL,
    address VARCHAR(300),
    detail_location VARCHAR(300) NOT NULL,
    description VARCHAR(3000),
    confirmed_date DATE NOT NULL,
    photo_lat DOUBLE PRECISION NOT NULL,
    photo_lng DOUBLE PRECISION NOT NULL,
    status VARCHAR(20) NOT NULL,
    review_note VARCHAR(2000),
    reviewer_user_id BIGINT REFERENCES users(user_id),
    reviewed_at TIMESTAMP WITH TIME ZONE,
    consented_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    photo_key VARCHAR(120),
    screenshot_key VARCHAR(120),
    version BIGINT NOT NULL DEFAULT 0,
    UNIQUE(user_id, request_key)
);
CREATE INDEX IF NOT EXISTS idx_facility_owner_created ON facility_applications(user_id, created_at);
CREATE TABLE IF NOT EXISTS registered_facilities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL UNIQUE REFERENCES facility_applications(id),
    category_key VARCHAR(80) NOT NULL,
    name VARCHAR(100) NOT NULL,
    address VARCHAR(300) NOT NULL,
    sido VARCHAR(40) NOT NULL,
    sigungu VARCHAR(80) NOT NULL,
    admin_dong VARCHAR(40) NOT NULL,
    lat DOUBLE PRECISION NOT NULL,
    lng DOUBLE PRECISION NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_registered_facility_region ON registered_facilities(category_key, sido, sigungu, admin_dong);
CREATE TABLE IF NOT EXISTS group_invite_links (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL REFERENCES work_groups(group_id),
    creator_user_id BIGINT NOT NULL REFERENCES users(user_id),
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked BOOLEAN NOT NULL DEFAULT FALSE,
    uses INTEGER NOT NULL DEFAULT 0
);
